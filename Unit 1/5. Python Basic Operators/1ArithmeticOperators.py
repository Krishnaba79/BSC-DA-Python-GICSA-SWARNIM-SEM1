a = 10
b = 3

# Addition
print("Addition:", a + b)

# Subtraction
print("Subtraction:", a - b)

# Multiplication
print("Multiplication:", a * b)

# Division
print("Division:", a / b)

# Modulus
print("Modulus:", a % b)
# Modulus returns the remainder of the division of a by b.

# Floor Division
print("Floor Division:", a // b)
# Floor division divides two numbers and returns the whole 
# number part (integer), removing the decimal part.

# Exponent
print("Exponent:", a ** b)
# (Exponent means power (10 × 10 × 10 = 1000))